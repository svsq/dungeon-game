#!/usr/bin/env python3
# python3 tools/talk_build.py: docs/talk/*.json (what the townsfolk say) into live/text_talk_ru.js; exit 2 on a dash or an unknown {@name}.
import json, glob, os, re, sys
ROOT = os.path.join(os.path.dirname(__file__), '..')
T, fails = {}, []
ru = open(os.path.join(ROOT, 'live/text_ru.js'), encoding='utf8').read()
def walk(v, at):
    if isinstance(v, str):
        if re.search('[—–]', v): fails.append(at + ': a dash')
        for k in re.findall(r'\{@(\w+)\}', v):
            if "'NAME.%s'" % k not in ru: fails.append(at + ': unknown {@%s}' % k)
    elif isinstance(v, list): [walk(x, at) for x in v]
    elif isinstance(v, dict): [walk(x, at + '.' + k) for k, x in v.items()]
for f in sorted(glob.glob(os.path.join(ROOT, 'docs/talk/*.json'))):
    d = json.load(open(f, encoding='utf8')); walk(d, os.path.basename(f))
    if os.path.basename(f) == 'topics.json':
        for r, L in d.items(): T.setdefault(r, {})['topics'] = L
    else:
        for r, v in d.items(): T.setdefault(r, {}).update(v)
for x in fails: print('FAIL', x)
if fails: sys.exit(2)
open(os.path.join(ROOT, 'live/text_talk_ru.js'), 'w', encoding='utf8').write('// live/text_talk_ru.js: what the townsfolk say; generated by tools/talk_build.py from docs/talk/*.json, edit those.\n(function (root) {\n  (root.TEXT || (root.TEXT = {})).talk = ' + json.dumps(T, ensure_ascii=False, separators=(',', ':')) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n')
print('talk:', ', '.join(T))
