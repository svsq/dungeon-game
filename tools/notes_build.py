#!/usr/bin/env python3
# python3 tools/notes_build.py [files...]: docs/notes/*.json (written by hand, kind note|secret|boss|hint) into live/text_notes_ru.js; exit 2 on a bad note.
import json, glob, sys, os, re
ROOT = os.path.join(os.path.dirname(__file__), '..')
files = sys.argv[1:] or sorted(glob.glob(os.path.join(ROOT, 'docs/notes/*.json')))
notes, ids, fails = [], set(), []
HOWS = ('banner', 'shelf', 'lever', 'plate', 'sconce', 'statue', 'levers', 'candles')
chains = {}
for f in files:
    for n in json.load(open(f, encoding='utf8')):
        i = n.get('id', '?'); where = os.path.basename(f) + ':' + i
        if i in ids: fails.append(where + ': duplicate id')
        ids.add(i)
        for k in ('kind', 'title', 'text'):
            if not n.get(k): fails.append(where + ': no ' + k)
        if n.get('kind') not in ('note', 'secret', 'boss', 'hint'): fails.append(where + ': bad kind')
        t = n.get('text', '') + n.get('title', '')
        if re.search('[—–]', t): fails.append(where + ': a dash')
        if len(n.get('text', '')) > 540: fails.append(where + ': too long')
        if n.get('kind') == 'hint' and n.get('how') not in HOWS: fails.append(where + ': bad how')
        if n.get('kind') == 'boss' and not (n.get('boss') and isinstance(n.get('floors'), list)): fails.append(where + ': boss note without boss/floors')
        if n.get('chain'): chains.setdefault((i.split('_')[0], n['chain']), []).append(n.get('part'))
        notes.append(n)
for c, p in chains.items():
    if sorted(p) != list(range(1, len(p) + 1)): fails.append(f'chain {c}: parts {sorted(p)}')
for h in HOWS:
    if sum(n.get('how') == h for n in notes) < 8: fails.append(f'hint: fewer than 8 notes for {h}')
for x in fails: print('FAIL', x)
if fails: sys.exit(2)
out = '// live/text_notes_ru.js: the notes found on the floors; generated by tools/notes_build.py from docs/notes/*.json, edit those.\n(function (root) {\n  (root.TEXT || (root.TEXT = {})).notes = ' + json.dumps(notes, ensure_ascii=False, separators=(',', ':')) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n'
open(os.path.join(ROOT, 'live/text_notes_ru.js'), 'w', encoding='utf8').write(out)
print(f'notes: {len(notes)} ({sum(n["kind"]=="note" for n in notes)} note, {sum(n["kind"]=="secret" for n in notes)} secret, {sum(n["kind"]=="boss" for n in notes)} boss, {sum(n["kind"]=="hint" for n in notes)} hint)')
