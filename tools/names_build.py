#!/usr/bin/env python3
# python3 tools/names_build.py: docs/names/*.json (elite names and epithets by monster group) into live/text_names_ru.js.
import json, glob, os
ROOT = os.path.join(os.path.dirname(__file__), '..')
T = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'docs/names/*.json'))): T.update(json.load(open(f, encoding='utf8')))
open(os.path.join(ROOT, 'live/text_names_ru.js'), 'w', encoding='utf8').write('// live/text_names_ru.js: elite names and epithets; generated by tools/names_build.py from docs/names/*.json, edit those.\n(function (root) {\n  (root.TEXT || (root.TEXT = {})).names = ' + json.dumps(T, ensure_ascii=False, separators=(',', ':')) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n')
print('groups', len(T), 'names', sum(len(v['names']) for v in T.values()), 'epithets', sum(len(v['adj']) for v in T.values()))
